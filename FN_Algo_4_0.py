def cari_varbl_dgn_konvergensi_continued_fraction(r_prev, r_curr, p_prev, p_curr, q_prev, q_curr, i, list_sementara):

  # Base Case r_curr = 0
  if r_curr == 0:
    return list_sementara[0], list_sementara[1], list_sementara[2], list_sementara[3], i;

  a_i = r_prev // r_curr
  r_next = r_prev % r_curr

  p_next = a_i * p_curr + p_prev
  q_next = a_i * q_curr + q_prev

  list_sementara[0].append(a_i)
  list_sementara[1].append(p_next)
  list_sementara[2].append(q_next)
  list_sementara[3].append(r_next)

  return cari_varbl_dgn_konvergensi_continued_fraction(r_curr, r_next, p_curr, p_next, q_curr, q_next, i+1, list_sementara)

def find_k(r, q, c, b, m):
  for k in range(1, m//2 + 1):
    if (r[2*k]/q[2*k] < c / b) and (c / b < r[2*k-2]/q[2*k-2]): # Edge case: X <= c/b < X
      return k

def phi(r2k_2, r2k_1, q2k_2, q2k_1, t):
  return (r2k_2 - t * r2k_1)/(q2k_2 + t * q2k_1)

def find_tStar(r2k_2, r2k_1, q2k_2, q2k_1, c, b, k, a_):
  for t in range(1, a_[2*k] + 1):
    if (phi(r2k_2, r2k_1, q2k_2, q2k_1, t) < c/b) and (c/b < phi(r2k_2, r2k_1, q2k_2, q2k_1, t - 1)): # Edge case: X <= c/b < X
      return t

def f_function(a_input, b_input, c_input):
  if (a_input < 1 or b_input < 1) or c_input < 1:
    return -3

  a, b, c = sorted([a_input, b_input, c_input])

  from math import gcd
  # Step 1: If gcd(a,b,c) != 1 then is not defined — exit.
  if gcd(gcd(a, b), c) != 1:
    return -1

  # Step 2: Compute a`, b`, c`
  d12 = gcd(a,b); d13 = gcd(a,c); d23 = gcd(b,c)
  a_hat = a // (d12 * d13); b_hat = b // (d23 * d12); c_hat = c // (d13 * d23)

  if d12 * d13 * d23 != 1:
    return d12 * d13 * d23 * f_function(a_hat, b_hat, c_hat)

  # Step 3: Sort a, b, c
  a_new, b_new, c_new = sorted([a_hat, b_hat, c_hat])

  #  Step 4: Solve for S
  if a == 1:
    s = -2
  else:
    s = (c * pow(b, -1, a)) % a

  if (b*s < c):
    return a * b + c;

  # Step 5: Euclidian Algorithm
  # Let, p_(-1) = 1 ||| p_0 = 0 ||| q_(-1) = 0 ||| q_0 = 1 ||| r_(-1) = a ||| r_0 = s
  p_1 = 1; p0 = 0;
  q_1 = 0; q0 = 1;

  a_idx, p, q, r, m = cari_varbl_dgn_konvergensi_continued_fraction(a, s, p_1, p0, q_1, q0, 0, [[0],[0],[1],[s]])


  # Step 6: Find k
  k = find_k(r, q, c, b, m)

  # Step 7: Find t*
  r2k_2 = r[2*k - 2]; r2k_1 = r[2*k - 1];
  q2k_2 = q[2*k - 2]; q2k_1 = q[2*k - 1];
  tStar = find_tStar(r2k_2, r2k_1, q2k_2, q2k_1, c, b, k, a_idx)


  # Step 8: Calculate and Exit
  x_prime = r2k_2 - (tStar - 1) * r2k_1
  x_doublePrime = r2k_2 - (tStar) * r2k_1
  y_prime = q2k_2 + (tStar - 1) * q2k_1
  y_doublePrime = q2k_2 + (tStar) * q2k_1
  return max(b*x_prime + c*q2k_1, b*r2k_1 + c*y_doublePrime)

